// 조사 고르기 테이블 테스트: 한글 받침, 숫자·영문의 읽는 소리, 판단할 수 없는 글자.
package title

import "testing"

func TestJosa(t *testing.T) {
	cases := []struct{ word, pair, want string }{
		{"홍길동", "을/를", "을"},
		{"김철수", "을/를", "를"},
		{"저장", "을/를", "을"},
		{"메뉴", "을/를", "를"},
		{"파일", "이/가", "이"},
		{"사과", "이/가", "가"},
		{"설정", "은/는", "은"},
		{"보기", "은/는", "는"},
		{"'확인'", "을/를", "을"}, // 끝 따옴표는 건너뛴다
		{"10", "을/를", "을"},   // 십
		{"2", "을/를", "를"},    // 이
		{"3", "이/가", "이"},    // 삼
		{"Windows 10", "을/를", "을"},
		{"PDF", "을/를", "를"},    // 피디에프
		{"URL", "을/를", "을"},    // 유알엘
		{"OK", "을/를", "를"},     // 오케이
		{"Login", "을/를", "을"},  // 로그인
		{"Save", "을/를", "를"},   // 세이브
		{"Chat", "을/를", "을"},   // 챗
		{"Desk", "을/를", "를"},   // 데스크
		{"String", "을/를", "을"}, // 스트링
		{"Blog", "을/를", "를"},   // 블로그
		{"●●●●", "을/를", "를"},   // 가린 비밀번호: 앱이 정한 표기라 "를"로 맞춘다
		{"漢字", "을/를", "을(를)"},
		{"", "을/를", "을(를)"},
	}
	for _, c := range cases {
		if got := Josa(c.word, c.pair); got != c.want {
			t.Errorf("Josa(%q, %q) = %q, want %q", c.word, c.pair, got, c.want)
		}
	}
}
